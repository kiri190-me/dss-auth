/**
 * ============================================================================
 * 메일에 적을 **통합 승인함 주소** — 환경에서 읽는다
 * ============================================================================
 * 🔴 승인함(`dss-approvals`)의 주소는 2026-10-23 현재 아직 정해지지 않았다.
 * 그래서 환경변수로 빼 두고, 없으면 메일에서 **주소 줄만 빠진다**
 * (approvals/mail-message.ts). 메일을 안 보내지는 않는다 — 「결재할 것이 있다」는
 * 사실은 주소 없이도 뜻이 있다.
 *
 * ── 🔵 나중에 DB 에서 읽게 될 자리다 ─────────────────────────────────────
 * 승인함이 `clients` 에 등록되는 날 그 주소는 `clients.launcher_url` 에 들어간다.
 * 그때는 이 환경변수 대신 거기서 읽는 편이 맞다 — 주소는 DB 에 있어야 하고
 * (docs/주소.md), 그래야 IP 가 바뀌어도 고칠 곳이 한 곳이다. 지금 그렇게 하지
 * 않는 까닭은 **등록이 아직 없어서**이고, 없는 것을 읽으면 메일마다 빈 자리가
 * 생긴다.
 *
 * 🔴 `config/env.ts` 에 두지 않은 까닭: 그 파일의 읽기는 **값이 없으면 던지는**
 * 쪽이다(인증 서버의 설정이 반쯤 빠진 채 도는 것이 가장 위험하므로). 이 값은
 * 없어도 포털이 멀쩡히 도는 값이라 규칙이 다르다.
 * ============================================================================
 */

export const APPROVAL_INBOX_URL_ENV = "APPROVAL_INBOX_URL";

/**
 * 적어 둔 승인함 주소. 없거나 모양이 틀렸으면 `null` 이다.
 *
 * 🔴 **`http`·`https` 만 받는다.** 메일 본문에 그대로 찍히는 글자라, 환경변수에
 * 엉뚱한 글자가 들어가면 그것이 전 직원에게 링크처럼 보이며 나간다.
 *
 * 🔵 끝의 `/` 는 떼지 않는다 — 사람이 적은 그대로 보여 주는 편이 낫다. 이 값으로
 * 다른 주소를 조립하지 않으므로 `iss` 대조 같은 사고가 날 자리가 없다.
 */
export function readApprovalInboxUrl(
  env: Record<string, string | undefined> = process.env
): string | null {
  const raw = env[APPROVAL_INBOX_URL_ENV]?.trim();
  if (!raw) return null;

  try {
    const url = new URL(raw);
    if (url.protocol !== "http:" && url.protocol !== "https:") return null;
    return raw;
  } catch {
    return null;
  }
}
