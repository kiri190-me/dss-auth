/**
 * 업데이트 소식 — 배포할 때마다 직원이 읽는 "무엇이 달라졌나".
 *
 * 왜 손으로 적나. 커밋 메시지에서 자동으로 뽑는 길도 있었지만 쓰지 않았다.
 * 이 저장소의 커밋은 "db:up·db:down·db:psql이 옛 상자를 켜던 것" 처럼
 * 개발자끼리 쓰는 말이고, 직원이 화면에서 겪는 변화와 1:1로 맞지도 않는다.
 * 사소한 커밋까지 그대로 흘러나오면 목록이 길어지기만 하고 정작 "내가 뭘 더
 * 할 수 있게 됐나"는 묻혀버린다. 그래서 여기에 사람이 골라 적는다.
 *
 * ⚠️ 이 화면은 로그인하지 않아도 열린다(/signin 에서 링크한다). 사내 주소·IP·
 *    무엇이 뚫려 있었는지는 적지 않는다. 보안 수정은 "고침"으로만 적고 내용은
 *    쓰지 않는다.
 *
 * 문구 규칙 — 기능 이름이 아니라 그 기능이 무엇을 해주는지로 쓴다.
 *   ✗ OIDC 백채널 로그아웃 구현
 *   ✓ 한 번 로그아웃하면 열어 둔 다른 시스템에서도 함께 로그아웃됩니다
 * 주소는 적지 않는다. IP가 바뀌어도 이 글이 틀린 말이 되지 않게 한다.
 * 직원 눈에 보이는 변화가 없는 배포라면 항목을 지어내지 말고 "겉으로 보이는
 * 변화는 없고 속을 손봤습니다" 한 줄이 낫다.
 *
 * ── 세 시스템을 함께 적는다 (2026-09-16 사용자 결정) ─────────────────
 * 직원은 시스템을 옮겨 다니며 쓰지 「어느 저장소의 일인지」로 나눠 생각하지 않는다.
 * 그래서 통합 로그인 · A/S 관리 · 계측기 관리의 소식을 여기 한곳에 모으고 항목마다
 * 어느 시스템인지 붙인다.
 *
 * 무엇을 맞바꾼 것인지 알고 쓴다 — dss-deploy/CLAUDE.md 는 「어느 한 시스템의 것은
 * 그 저장소에」라고 적어 두었다. 여기로 넘어오는 것은 **글**이지 코드 의존이 아니다.
 * 포털은 A/S 를 부르지 않고, A/S 가 멈춰도 이 화면은 멀쩡하다. 대신 **A/S 만 배포해도
 * 그 소식을 실으려면 포털도 배포해야 한다** — 그 값을 치르기로 했다.
 *
 * ── 배포할 때 할 일 ─────────────────────────────────────────────────
 *   1. RELEASES 맨 앞에 이번 배포 항목을 더한다 — 배포하는 그 커밋에서.
 *      미리 적어두면 화면은 아직 돌지도 않는 버전을 광고하게 된다.
 *   2. version 은 **그 시스템의 도커 이미지 태그**다(dss-as:1.3 이면 "1.3").
 *      시스템마다 따로 센다 — 통합 로그인 1.3 과 A/S 1.3 은 남남이다.
 *   3. **통합 로그인** 항목을 더했으면 package.json 의 version 도 같이 올린다.
 *      (안 하면 npm test 가 잡는다. 다른 시스템 항목은 package.json 과 무관하다.)
 *   4. 그 시스템의 도커 이미지를 같은 번호로 굽는다 — docker build -t dss-as:1.3 .
 *
 * 앱 이미지가 바뀌지 않았는데 직원이 겪는 변화가 있을 수도 있다(설정 · 서버 쪽 일).
 * 그럴 때는 **지금 도는 이미지의 번호를 그대로 쓴다** — 번호는 「무엇이 돌고 있나」이지
 * 「몇 번째 글이냐」가 아니다.
 * ───────────────────────────────────────────────────────────────
 */

/** 항목의 갈래. 한눈에 성격을 알 수 있게 셋으로만 나눈다. */
