import { pgTable, timestamp, uuid } from "drizzle-orm/pg-core";
import { users } from "./users";

/**
 * ============================================================================
 * 「이 사람이 통합 승인함을 마지막으로 연 때」 — 한 사람에 한 줄
 * ============================================================================
 * 이 한 칸으로 `/apps` 의 승인함 타일에 붙는 **빨간 점**이 전부 정해진다
 * (approvals/tile-dot.ts):
 *
 *   점  =  그 사람의 결재 대기 건 중 `requestedAt > seen_at` 인 것이 있는가
 *
 * 승인함을 열면 이 값이 갱신되어 점이 사라지고, 결재가 **해소되면** 그 건이
 * 세 시스템의 목록에서 빠지므로 세어지지 않아 역시 사라진다. 🔴 **「해소됐다」를
 * 적어 두는 칸이 없는 것은 빠뜨린 것이 아니다** — 결재의 주인은 각 시스템이고
 * 포털은 「지금 남아 있는 것」만 물어볼 수 있다(approval_mail_deliveries 의
 * 「이 표의 행을 지우면 그 메일이 다시 나간다」와 같은 사정이다).
 *
 * ── 🔴 왜 `users` 에 칸을 더하지 않았나 ───────────────────────────────────
 * ① `users` 는 **그 사람이 누구인가**를 담는 표다. 「승인함을 열었다」는 화면
 *    표시 하나를 위한 자취라서, 지워져도 아무것도 잃지 않는 쪽에 둔다.
 * ② 승인함을 열 때마다 `users` 에 UPDATE 가 돌면, 사람 정보를 고치는 쓰기와
 *    같은 행을 두고 다툰다. 하루에 몇 번뿐인 쓰기와 화면을 열 때마다의 쓰기를
 *    같은 표에 섞을 까닭이 없다.
 * ③ 포털의 다른 「사람별 표시」(알림 지움 · 확인)가 전부 딸린 표라, 같은 모양으로
 *    두면 다음 사람이 한눈에 짝을 찾는다.
 *
 * 🔵 「칸을 더하면 그 표의 전체 조회가 새 칸을 싣는다」는 걱정은 **이 저장소에는
 * 해당하지 않는다** — 실측해 보면 `src/lib/db` 아래에 칸을 안 적은 `.select()`
 * 가 한 곳도 없다. 그 사고는 다른 저장소에서 난 일이고, 여기서 표를 나눈 까닭은
 * 위 셋이다.
 *
 * ── 🔴 열쇠가 `user_id` **자체**다 — 이웃 표들과 다른 모양 ────────────────
 * `notification_dismissals` · `approval_mail_deliveries` 는 `id uuid` 를 두고
 * 유일 색인을 따로 걸지만, 저쪽은 **한 사람에 여러 줄**이라 그렇다. 여기는 한
 * 사람에 한 줄뿐이라 `user_id` 가 그대로 기본키다. 군더더기 `id` 와 색인 하나가
 * 줄고, 쓰는 쪽이 `onConflictDoUpdate` 로 겨눌 자리가 분명해진다
 * (mutations/approval-inbox-views.ts).
 *
 * ── 보관 기간을 두지 않았다 ───────────────────────────────────────────────
 * 사람 수만큼만 쌓이고(사내 인원), 사람이 지워지면 `cascade` 로 함께 간다.
 * 걷어 갈 것이 없으므로 db/retention.ts 에 줄을 더하지 않았다.
 */
export const approvalInboxViews = pgTable("approval_inbox_views", {
  /**
   * 포털 `users.id`.
   *
   * 🔴 **`cascade` 다** — `notification_dismissals` 와 같은 판단이다. 포털의
   * 외래키 대부분은 `restrict` 지만(감사 로그 · 권한 부여 · 세션처럼 남아야 할
   * 기록), 이 표는 **화면 표시를 위한 자취**라서 그것이 계정 삭제를 막아 서면
   * 곤란하다.
   */
  userId: uuid("user_id")
    .primaryKey()
    .references(() => users.id, { onDelete: "cascade" }),
  /**
   * 승인함을 연 때.
   *
   * 🔴 쓰는 쪽은 **값을 직접 적어 넣는다** — 결재함을 모으기 **전**의 시각이다
   * (approvals/screen-request.ts). 모으는 데 최대 1.5초가 걸리는데 그 뒤의
   * 시각을 적으면, 모으는 동안 올라온 결재가 「이미 본 것」으로 묻힌다.
   * `defaultNow()` 는 손으로 한 줄 넣어 볼 때를 위한 것이고 앱은 쓰지 않는다.
   */
  seenAt: timestamp("seen_at", { withTimezone: true }).notNull().defaultNow(),
});
