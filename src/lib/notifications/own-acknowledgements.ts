import { acknowledgedItemKeys, type AcknowledgementState } from "./acknowledgements";
import { parseDismissalKey, type SiteDismissalFeed } from "./dismissals";
import type { PortalNotificationItem } from "./merge";

/**
 * ============================================================================
 * 사이트가 **제 알림**도 확인(✓)으로 거를 수 있게 — 내려보낼 열쇠를 고른다
 * ============================================================================
 * 포털이 사이트에 알림을 내줄 때 **그 사이트 몫의 지운(✕) 열쇠**는 함께 보낸다
 * (dismissals.ts 의 `applySiteDismissals`). 확인(✓)은 안 보내고 있었다. 그래서
 * 이런 구멍이 있었다:
 *
 *   [재고부족] 을 A/S 종에서 ✓
 *     → 포털에 적힘 → A/S · PO · 게시판에서 사라짐          ✅
 *     → 🔴 재고관리 **제 종에서는 그대로 남음** — 제 알림은 제 DB 에서 그리는데
 *        포털이 「이건 확인됐다」를 안 알려 주기 때문이다.
 *
 * 이 파일이 그 한 칸(`acknowledged`)을 만든다.
 *
 * ── 🔴 왜 **열쇠 목록**을 내려보내고, 재료를 내려보내지 않는가 ──────────────
 * 확인이 거르는 조건은 **셋이 모두** 맞아야 한다(acknowledgements.ts 머리말):
 * ① 기록이 있고 ② 지문이 지금 내용과 같고 ③ 분류가 `INFO` 다.
 *
 * 길이 둘 있었다.
 *
 *  **(가) 포털이 끝까지 판단한다** — 셋을 포털이 다 보고 **뺄 열쇠만** 내려보낸다.
 *  **(나) 재료를 내려보내고 사이트가 판단한다** — 지문과 분류를 함께 보낸다.
 *
 * 🔴 **(나)를 버렸다.** 까닭은 ② 다. 지문을 사이트가 계산하면 **지문 짓는 규칙이
 * 일곱 벌**(포털 + 사이트 여섯)이 된다. 그 규칙은 `contentDigest` 의 주석이 길게
 * 적어 둔 대로 「subject 의 길이를 앞에 적고 이어 붙인 뒤 sha256 의 앞 16자」인데,
 * 한 사이트가 이것을 조금이라도 다르게 적으면 **그 사이트에서만 확인이 영영 안
 * 먹힌다.** 오류는 한 줄도 안 난다 — 지문이 늘 다르니 늘 「내용이 바뀌었다」로
 * 읽힐 뿐이다. 이 저장소들에서 **같은 것의 열쇠가 시스템마다 달라** 겪은 적이
 * 있는 종류의 사고이고, 그때도 단위 시험으로는 잡히지 않았다. ③ 도 같다 —
 * 분류를 내려보내면 「모르면 `ACTION`」(purposes.ts 의 기본값)을 여섯 곳에 또
 * 적어야 하고, 한 곳이 「모르면 숨긴다」로 적으면 **승인용 알림이 조용히 사라진다.**
 *
 * 🔵 (가)는 판단이 포털 한 곳에 남는다. 관리자가 분류를 `INFO` 로 바꾸면 **그날로
 * 일곱 사이트가 전부 따라온다** — 사이트는 받은 열쇠를 빼기만 하기 때문이다.
 *
 * ── 🔴 (가)가 치르는 값: 포털이 **부른 사이트에게도 묻는다** ────────────────
 * ②·③ 을 보려면 **그 줄 자체**가 있어야 하는데, 읽기 통로가 내주는 목록에는
 * 부른 사이트의 줄이 없다(site-service.ts 맨 위의 `exceptClientId`). 그래서
 * site-service.ts 가 **부른 사이트에게도 한 번 묻는다.** 그 왕복과 되돌기를
 * 실측으로 확인한 결과는 저쪽 `ownFeed` 곁에 적어 두었다.
 *
 * ── 🔴 `dismissed` 와 **섞지 않는다** ─────────────────────────────────────
 * 수명이 정반대다. 지움은 로그아웃하면 돌아오고(그 표는 로그아웃 때 비워진다),
 * 확인은 안 돌아온다. 한 칸에 담으면 사이트가 확인을 **지움으로 읽어** 그대로
 * 두는데, 그러면 뜻은 우연히 맞고 **수명이 틀린다** — 로그아웃한 뒤에도 안
 * 돌아오는 줄이 지움 쪽에 섞여 있게 된다. 반대로 사이트가 지움을 확인으로 읽으면
 * **영구히 빼 버린다.** 칸을 둘로 두면 그 길이 아예 없다.
 * ============================================================================
 */

/**
 * 사이트에 내줄 때의 마지막 모양 — `dismissed` 옆에 **확인 몫**이 한 칸 더 붙는다.
 *
 * 🔴 이것이 사이트 여섯이 읽을 **계약**이다. 모양을 바꾸면 저쪽이 조용히 깨진다
 * (모르는 칸은 JSON 을 읽는 쪽에서 무시되므로 **오류가 안 난다**).
 * 글로 적힌 규격은 docs/사이트-알림-통로.md 에 있다.
 */
export type SiteNotificationFeed = SiteDismissalFeed & {
  /**
   * 🔴 **부른 사이트 몫만.** 사이트가 제 알림 목록에서 이 열쇠들을 뺀다.
   *
   * 🔴 `dismissed` 와 **다른 칸이고 뜻도 다르다.** 여기 든 줄은 「해소됐다」라
   * 로그아웃해도 안 돌아오고, `dismissed` 에 든 줄은 「지금은 그만 보겠다」라
   * 로그아웃하면 돌아온다. 사이트가 둘을 한 뭉치로 만들면 수명이 섞인다.
   *
   * 🔵 열쇠 모양은 `items[].key` 와 같다(`{client_id}:{id}`). 뺄 것이 없으면
   * **빈 배열**이다 — 칸이 있다 없다 하지 않는다.
   */
  acknowledged: string[];
};

/**
 * **부른 사이트 제 줄 가운데 「빼라」고 말해 줄 열쇠.**
 *
 * 조건 셋을 보는 일은 `acknowledgedItemKeys` 하나에 맡긴다 — 포털 제 종이 쓰는
 * 바로 그 함수다. 🔴 **여기에 조건을 다시 적지 않는다.** 두 벌이 되면 「포털
 * 종에서는 사라졌는데 사이트 종에서는 안 사라진다」가 되고, 그 어긋남은 신고로만
 * 드러난다(증상이 바로 이 조각이 메우려던 구멍과 똑같이 생겼다).
 *
 * ── 🔴 받는 것은 **그 사이트의 줄만** 든 목록이다 ──────────────────────────
 * 남의 시스템 줄이 섞여 들어오면 그 열쇠가 사이트로 내려간다. 사이트는 제
 * 목록에서 `{자기 client_id}:{id}` 를 빼는 데 그 열쇠를 쓰므로 **맞아떨어지는 줄이
 * 없어 아무 일도 안 일어나지만**, 그 사람이 **다른 시스템에서 무엇을 확인했는지**가
 * 통째로 넘어간다. 열쇠의 `id` 에는 `REPAIR_CASE_APPROVAL:RC-2026-0001` 처럼 업무
 * 식별자가 들어 있다 — 알림 본문은 걸러서 안 보내면서 그 알림의 열쇠를 보내는 것은
 * 앞뒤가 맞지 않는다(applySiteDismissals 가 같은 까닭으로 제 몫만 고른다).
 *
 * 🔴 그래서 **부르는 쪽을 믿지 않고 여기서 한 번 더 고른다.** 판정은
 * `parseDismissalKey` 하나다 — `startsWith(clientId + ":")` 로 적으면 열쇠를
 * 가르는 규칙이 두 벌이 된다(저쪽 주석: 첫 `:` 에서만 가른다).
 */
export function ownAcknowledgedKeys(params: {
  /** 🔴 **부른 사이트가 낸 줄**. 포털이 그 사이트에 물어서 받아 온 것이다. */
  ownItems: readonly PortalNotificationItem[];
  /** 확인 기록(지문)과 분류. 포털 제 종이 쓰는 것과 같은 값이다. */
  state: AcknowledgementState;
  /** 부른 사이트의 `client_id`. */
  clientId: string;
}): string[] {
  const keys: string[] = [];
  for (const key of acknowledgedItemKeys(params.ownItems, params.state)) {
    if (parseDismissalKey(key)?.clientId === params.clientId) keys.push(key);
  }
  return keys;
}

/**
 * 거른 feed 에 **확인 몫 한 칸**을 얹는다.
 *
 * 🔴 **`dismissed` 에 손대지 않는다.** 이 함수가 따로 있는 까닭이 그것이다 —
 * 얹는 자리를 한 곳으로 묶어 두면 「확인 열쇠를 `dismissed` 에 밀어 넣는」 길이
 * 생기지 않고, 그 성질을 시험이 이 함수 하나로 못 박을 수 있다.
 *
 * 🔴 **받은 feed 를 제자리에서 고치지 않는다.** 들어오는 값은 포털의 30초 캐시에
 * 든 객체에서 뻗어 나온 것이라, 제자리에서 칸을 더하면 그 사본이 캐시에 눌러앉는다
 * (까닭은 dismissals.ts 의 applyDismissals 주석에 길게 적혀 있다).
 *
 * ── 🔴 「뺄 것이 없다」와 「모른다」가 같은 값이다 — 알고 그렇게 했다 ────────
 * 못 물어봤을 때도 `acknowledged: []` 다. `dismissed` 가 같은 자리에서 내린 판단과
 * **같은 판단**이고(site-service.ts 의 withoutDismissed), 까닭도 같다:
 *
 *   · 「안 뺀다」가 틀리면 — 이미 처리한 알림이 한 번 더 보인다. 눈에 거슬린다.
 *   · 「뺀다」가 틀리면 — 🔴 **아직 안 한 일이 안 보인다.** 놓치고, 놓쳤다는 사실도
 *     모른다.
 *
 * 한쪽은 시끄러운 불편이고 한쪽은 조용한 사고다. 모를 때는 시끄러운 쪽으로 간다 —
 * purposes.ts 의 기본값이 `ACTION` 인 것과 같은 저울이다.
 *
 * 🔵 둘을 가르는 표시는 `degraded` 다. 「못 물어봤다」는 그 칸으로 말하고, 이 칸은
 * 언제나 「지금 뺄 수 있는 것」만 담는다.
 */
export function withOwnAcknowledgements(
  feed: SiteDismissalFeed,
  acknowledged: string[]
): SiteNotificationFeed {
  return { ...feed, acknowledged };
}
